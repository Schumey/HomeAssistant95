const findAnchor = (ev) =>
  ev.composedPath().find((el) => el instanceof Element && el.hasAttribute?.("data-ha95-menu"));

function attach(sb) {
  if (!sb?.shadowRoot || sb.__ha95menu) return;
  sb.__ha95menu = true;
  const root = sb.shadowRoot;

  const style = document.createElement("style");
  style.textContent = SIDEBAR_CSS + MENU_CSS;
  root.appendChild(style);
  loadConfig().then(() => decorate(root));

  const addArrows = () =>
    root.querySelectorAll("[data-ha95-menu]").forEach((el) => {
      if (el.querySelector(":scope > .ha95-sb-arrow")) return;
      const a = document.createElement("span");
      a.className = "ha95-sb-arrow";
      a.slot = "end";
      a.textContent = "▶";
      el.appendChild(a);
    });
  addArrows();
  // Höchstens einmal pro Frame, damit eigene Änderungen keine Kette auslösen.
  // Schutz: Läuft es trotzdem drei Sekunden am Stück mehr als GUARD_LIMIT-mal
  // pro Sekunde (eine Schleife mit dem Observer), schaltet sich das Schmücken
  // ab, statt die ganze Oberfläche einzufrieren. Die Menüs funktionieren weiter.
  let queued = false;
  let runs = 0;
  let busySeconds = 0;
  let windowStart = performance.now();
  const observer = new MutationObserver(() => {
    if (queued) return;
    queued = true;
    requestAnimationFrame(() => {
      queued = false;
      const now = performance.now();
      if (now - windowStart > 1000) {
        busySeconds = runs > GUARD_LIMIT && now - windowStart < 2000 ? busySeconds + 1 : 0;
        windowStart = now;
        runs = 0;
      }
      runs++;
      if (busySeconds >= 3) {
        observer.disconnect();
        console.warn(
          `HA95 Startmenü: Seitenleiste ändert sich mehr als ${GUARD_LIMIT}-mal pro Sekunde, ` +
            "Streifen und bunte Icons werden nicht mehr nachgeführt (Schutz vor Endlosschleife)."
        );
        return;
      }
      try {
        addArrows();
        decorate(root);
      } catch (err) {
        console.warn("HA95 Startmenü: Fehler beim Schmücken der Seitenleiste", err);
      }
    });
  });
  observer.observe(root, { subtree: true, childList: true, attributes: true, attributeFilter: ["data-ha95-menu", "icon", "href"] });

  root.addEventListener(
    "pointerover",
    mouseOnly((ev) => {
      const anchor = findAnchor(ev);
      if (anchor) {
        cancelClose();
        openRootMenu(anchor);
      }
    })
  );
  root.addEventListener(
    "pointerout",
    mouseOnly((ev) => {
      if (findAnchor(ev) && !findAnchor({ composedPath: () => [ev.relatedTarget] })) scheduleClose();
    })
  );
  // Doppelklick auf den Titel mit der Uhr wie auf die Uhr der Taskleiste,
  // auf Touch-Bildschirmen reicht einmal Tippen
  const onTitle = (ev) => ev.composedPath().some((el) => el.classList?.contains("title"));
  root.addEventListener("dblclick", (ev) => config?.clock && onTitle(ev) && openClock());
  root.addEventListener("pointerup", (ev) => {
    if (ev.pointerType === "touch" && config?.clock && onTitle(ev)) openClock();
  });
  // Klick/Tippen öffnet das Menü (für Touch), statt zu navigieren
  root.addEventListener(
    "click",
    (ev) => {
      const anchor = findAnchor(ev);
      if (!anchor) return;
      ev.preventDefault();
      ev.stopPropagation();
      if (openMenus[0]?.anchor === anchor) closeAll();
      else openRootMenu(anchor);
    },
    true
  );
}

