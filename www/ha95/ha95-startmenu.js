const deepQuery = (selector, root = document) => {
  let found = null;
  const walk = (node) => {
    for (const el of node.querySelectorAll("*")) {
      if (found) return;
      if (el.matches(selector)) {
        found = el;
        return;
      }
      if (el.shadowRoot) walk(el.shadowRoot);
    }
  };
  walk(root);
  return found;
};

