const colorName = (icon) => {
  // Präfix weg (mdi:, ha95:, hacs: …), dann zählt nur der Name
  const name = String(icon || "").replace(/^[a-z0-9_-]+:/, "");
  const real = COLOR_ALIASES[name] || name;
  return real in COLOR_ICONS ? real : null;
};

// Raster → SVG mit einem Pfad je Farbe (zeilenweise Rechtecke, pixelgenau)
const svgCache = new Map();
const colorSvg = (name) => {
  if (!name) return "";
  if (svgCache.has(name)) return svgCache.get(name);
  const runs = {};
  COLOR_ICONS[name]
    .trim()
    .split("\n")
    .forEach((row, y) => {
      for (let x = 0; x < row.length; ) {
        const c = row[x];
        let w = 1;
        while (row[x + w] === c) w++;
        if (c !== ".") (runs[c] ||= []).push(`M${x} ${y}h${w}v1h${-w}z`);
        x += w;
      }
    });
  const paths = Object.entries(runs)
    .map(([c, d]) => `<path fill="${COLOR_PALETTE[c]}" d="${d.join("")}"/>`)
    .join("");
  const svg = `<svg class="ha95-cicon" viewBox="0 0 24 24" shape-rendering="crispEdges" aria-hidden="true">${paths}</svg>`;
  svgCache.set(name, svg);
  return svg;
};

