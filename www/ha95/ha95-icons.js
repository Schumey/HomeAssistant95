const FALLBACK = "help";
const cache = new Map();
// Pfade, die schon im Pixelraster liegen (werden nicht nochmal verpixelt)
const pixelPaths = new Set();

const run = (x, y, w) => `M${x} ${y}h${w}v1h${-w}z`;

// Raster → zwei SVG-Pfade (zeilenweise Rechtecke, bleiben pixelgenau)
const toIcon = (grid) => {
  let path = "";
  let secondaryPath = "";
  grid.trim().split("\n").forEach((row, y) => {
    for (let x = 0; x < row.length; ) {
      const c = row[x];
      let end = x + 1;
      while (row[end] === c) end++;
      if (c === "#") path += run(x, y, end - x);
      else if (c === "+") secondaryPath += run(x, y, end - x);
      x = end;
    }
  });
  pixelPaths.add(path).add(secondaryPath);
  return { path, secondaryPath: secondaryPath || undefined, viewBox: "0 0 24 24" };
};

const iconName = (name) => (name in ICONS ? name : ALIASES[name]);

const getIcon = async (name) => {
  let key = iconName(name);
  if (!key) {
    console.warn(`HA 95: Icon "ha95:${name}" gibt es nicht`);
    key = FALLBACK;
  }
  if (!cache.has(key)) cache.set(key, toIcon(ICONS[key]));
  return cache.get(key);
};

const getIconList = async () =>
  Object.keys(ICONS).map((name) => ({ name, keywords: name.split("-") }));

window.customIcons = window.customIcons || {};
window.customIcons.ha95 = { getIcon, getIconList };

// ---------- Automatik ----------

const options = new URL(import.meta.url).searchParams;

// Beliebigen 24er-SVG-Pfad auf das Pixelraster bringen: 4×4 Stichproben
// pro Pixel, ab halber Deckung wird der Pixel gesetzt.
const SAMPLES = 4;
const pixelCache = new Map();
let ctx;

const pixelate = (d) => {
  if (!d || pixelPaths.has(d)) return d;
  if (pixelCache.has(d)) return pixelCache.get(d);
  const size = 24 * SAMPLES;
  ctx ??= Object.assign(document.createElement("canvas"), { width: size, height: size })
    .getContext("2d", { willReadFrequently: true });
  ctx.setTransform(1, 0, 0, 1, 0, 0);
  ctx.clearRect(0, 0, size, size);
  ctx.setTransform(SAMPLES, 0, 0, SAMPLES, 0, 0);
  ctx.fill(new Path2D(d));
  const alpha = ctx.getImageData(0, 0, size, size).data;
  const on = (x, y) => {
    let n = 0;
    for (let sy = 0; sy < SAMPLES; sy++) {
      for (let sx = 0; sx < SAMPLES; sx++) {
        if (alpha[((y * SAMPLES + sy) * size + x * SAMPLES + sx) * 4 + 3] > 127) n++;
      }
    }
    return n * 2 >= SAMPLES * SAMPLES;
  };
  let out = "";
  for (let y = 0; y < 24; y++) {
    let start = -1;
    for (let x = 0; x <= 24; x++) {
      if (x < 24 && on(x, y)) {
        if (start < 0) start = x;
      } else if (start >= 0) {
        out += run(start, y, x - start);
        start = -1;
      }
    }
  }
  out ||= d; // sehr feine Formen lieber unverändert lassen
  pixelPaths.add(out);
  pixelCache.set(d, out);
  return out;
};

const replaceIcon = (icon) => {
  const name = /^mdi:(.+)$/.exec(icon || "")?.[1];
  return name && iconName(name) ? `ha95:${name}` : icon;
};

// Vor jedem Neuzeichnen eingreifen. Bereits gezeichnete Elemente werden
// einmal angestoßen, damit sie die Änderung auch übernehmen.
const hook = (tag, apply, refresh) =>
  customElements.whenDefined(tag).then(() => {
    const proto = customElements.get(tag).prototype;
    const willUpdate = proto.willUpdate;
    proto.willUpdate = function (changed) {
      apply(this);
      return willUpdate.call(this, changed);
    };
    const visit = (root) => {
      root.querySelectorAll("*").forEach((el) => {
        if (el.localName === tag) refresh(el);
        if (el.shadowRoot) visit(el.shadowRoot);
      });
    };
    visit(document);
  });

if (options.has("replace")) {
  hook(
    "ha-icon",
    (el) => {
      el.icon = replaceIcon(el.icon);
    },
    (el) => {
      el.icon = replaceIcon(el.icon);
    }
  );
}

if (options.has("pixelate")) {
  hook(
    "ha-svg-icon",
    (el) => {
      if (el.viewBox && el.viewBox !== "0 0 24 24") return;
      el.path = pixelate(el.path);
      el.secondaryPath = pixelate(el.secondaryPath);
    },
    (el) => el.requestUpdate()
  );
}
