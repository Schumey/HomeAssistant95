const FALLBACK = "help";
const cache = new Map();

// Raster → zwei SVG-Pfade (zeilenweise Rechtecke, bleiben pixelgenau)
const toIcon = (grid) => {
  let path = "";
  let secondaryPath = "";
  grid.trim().split("\n").forEach((row, y) => {
    for (let x = 0; x < row.length; ) {
      const c = row[x];
      let end = x + 1;
      while (row[end] === c) end++;
      const run = `M${x} ${y}h${end - x}v1h${x - end}z`;
      if (c === "#") path += run;
      else if (c === "+") secondaryPath += run;
      x = end;
    }
  });
  return { path, secondaryPath: secondaryPath || undefined, viewBox: "0 0 24 24" };
};

const getIcon = async (name) => {
  const key = name in ICONS ? name : ALIASES[name] ?? FALLBACK;
  if (key === FALLBACK && name !== FALLBACK) {
    console.warn(`HA 95: Icon "ha95:${name}" gibt es nicht`);
  }
  if (!cache.has(key)) cache.set(key, toIcon(ICONS[key]));
  return cache.get(key);
};

const getIconList = async () =>
  Object.keys(ICONS).map((name) => ({ name, keywords: name.split("-") }));

window.customIcons = window.customIcons || {};
window.customIcons.ha95 = { getIcon, getIconList };
